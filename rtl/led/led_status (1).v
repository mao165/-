`timescale 1ns / 1ps
//******************************************************************************
//  文件名:		led_status.v
//  模块名:		led_status
//  功能描述:	LED状态指示模块
//				- 根据输入状态控制LED显示
//				- 支持常灭/常亮/闪烁三种模式
//				- 闪烁频率约1.49Hz（周期约671ms）
//------------------------------------------------------------------------------
//  状态编码:
//  ┌──────────┬──────────────┬──────────────┐
//  │  status  │   LED状态    │     含义     │
//  ├──────────┼──────────────┼──────────────┤
//  │   2'b00  │   常灭       │   未锁定     │
//  │   2'b01  │   常亮       │   已锁定     │
//  │   其他   │   闪烁       │   异常       │
//  └──────────┴──────────────┴──────────────┘


module led_status(
	//==========================================================================
	// 系统信号
	//==========================================================================
	input	wire					clk,				// 用户时钟
	input	wire					rst_n,				// 系统复位（低有效）
	
	//==========================================================================
	// 状态控制
	//==========================================================================
	input	wire	[1:0]			status,				// LED状态控制
	
	//==========================================================================
	// LED输出
	//==========================================================================
	output	reg						led					// LED控制（高电平点亮）
);

//==============================================================================
// 参数定义
//==============================================================================

// 闪烁周期 = 2^25 * 20ns ≈ 671ms，频率约1.49Hz
localparam	BLINK_CNT_WIDTH	= 25;

//==============================================================================
// 内部信号定义
//==============================================================================

reg		[BLINK_CNT_WIDTH-1:0]	counter;			// 闪烁计数器
wire							blink_signal;		// 闪烁信号

//==============================================================================
// 闪烁信号生成
//==============================================================================
// 取计数器最高位，每2^24个时钟翻转一次（半周期≈335ms）
assign blink_signal = counter[BLINK_CNT_WIDTH-1];

//==============================================================================
// LED控制逻辑
//==============================================================================
always @(posedge clk or negedge rst_n) begin
	if (!rst_n) begin
		counter	<= {BLINK_CNT_WIDTH{1'b0}};
		led		<= 1'b0;
	end
	else begin
		counter <= counter + 1'b1;
		
		case (status)
			2'b00:   led <= 1'b0;				// 常灭
			2'b01:   led <= 1'b1;				// 常亮
			default: led <= blink_signal;		// 闪烁
		endcase
	end
end

endmodule