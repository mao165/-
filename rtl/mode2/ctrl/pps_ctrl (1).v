`timescale 1ns / 1ps
//******************************************************************************
//  文件名:     pps_ctrl.v
//  模块名:     pps_ctrl
//  功能描述:   PPS控制模块 (clk域)
//              - 统计PPS脉冲数量
//              - 控制系统运行状态 sys_running (第3个PPS后启动)
//------------------------------------------------------------------------------
//  设计说明:
//  
//  Step0重构后，sec_idx和地址生成已移至ddr3_addr_ctrl模块 (ui_clk域)
//  本模块只保留clk域需要的控制逻辑:
//  - pps_cnt: 统计PPS数量，用于判断系统启动条件
//  - sys_running: 第3个PPS后为1，控制pack_enable
//------------------------------------------------------------------------------
//  时序说明:
//        PPS1        PPS2        PPS3        PPS4        PPS5
//         │           │           │           │           │
//         ▼           ▼           ▼           ▼           ▼
//  ───────┼───────────┼───────────┼───────────┼───────────┼─────────
//         │           │           │           │           │
//  pps_cnt│     1     │     2     │     3     │     4     │     5
//         │           │           │           │           │
//  sys_run│     0     │     0     │     1     │     1     │     1
//
//  说明:
//  - 前2个PPS用于系统稳定，不进行有效数据采集
//  - 第3个PPS后 sys_running=1，开始正式采集
//------------------------------------------------------------------------------


module pps_ctrl(
    //==========================================================================
    // 系统信号
    //==========================================================================
    input   wire                clk,                // 用户时钟
    input   wire                rst_n,              // 复位（低有效）
    
    //==========================================================================
    // DDR3状态
    //==========================================================================
    input   wire                ddr_init_done,      // DDR3初始化完成
    
    //==========================================================================
    // PPS输入
    //==========================================================================
    input   wire                pps_pulse,          // PPS脉冲 (单周期)
    
    //==========================================================================
    // 控制输出
    //==========================================================================
    output  reg                 sys_running,        // 系统运行标志
                                                    // 第3个PPS后为1
    output  reg     [7:0]       pps_cnt             // PPS计数器 (调试用)
);

//==============================================================================
// 参数定义
//==============================================================================

//------------------------------------------------------------------------------
// 系统启动条件
// 需要等待3个PPS后才开始正式运行
// 原因: 前2秒用于系统稳定，避免不完整的秒数据
//------------------------------------------------------------------------------
localparam  [7:0]   PPS_CNT_START = 8'd3;           // 第3个PPS后启动

//==============================================================================
// PPS计数器
// - DDR3初始化完成后才开始计数
// - 每个PPS脉冲+1
// - 用于判断系统启动条件
//==============================================================================
always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        pps_cnt <= 8'd0;
    end
    else if (!ddr_init_done) begin
        pps_cnt <= 8'd0;
    end
    else if (ddr_init_done && pps_pulse) begin
        if (pps_cnt < 8'd255) begin
            pps_cnt <= pps_cnt + 1'b1;              // 防止溢出
        end
    end
end

//==============================================================================
// 系统运行标志
// - 第3个PPS后置1，表示系统进入正常运行状态
// - 之前的数据不参与触发与输出
//==============================================================================
always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        sys_running <= 1'b0;
    end
    else if (!ddr_init_done) begin
        sys_running <= 1'b0;
    end
    else if ((pps_cnt >= PPS_CNT_START) ||
             (ddr_init_done && pps_pulse &&
              (pps_cnt >= PPS_CNT_START - 8'd1))) begin
        sys_running <= 1'b1;                        // 第3个PPS后启动
    end
end

endmodule
