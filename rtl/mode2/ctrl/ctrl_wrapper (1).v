`timescale 1ns / 1ps
//******************************************************************************
//  文件名:     ctrl_wrapper.v
//  模块名:     ctrl_wrapper
//  功能描述:   控制逻辑封装模块 (clk域)
//              
//  主要功能:
//  1. 使用DDR控制器已同步到clk域的唯一初始化完成信号
//  2. PPS控制封装 - 管理系统启动状态
//  3. 使能信号生成 - 控制数据打包模块的启动时机
//------------------------------------------------------------------------------


module ctrl_wrapper(
    //==========================================================================
    // 系统信号
    //==========================================================================
    input   wire                clk,                // 用户时钟
    input   wire                rst_n,              // 复位（低有效）
    
    //==========================================================================
    // DDR3状态输入
    //==========================================================================
    input   wire                ddr_init_done_native,// DDR3初始化完成（已同步到clk域）
    input   wire                wfifo_wr_rst_busy,  // 写FIFO复位忙标志
    
    //==========================================================================
    // PPS输入
    //==========================================================================
    input   wire                pps_pulse,          // PPS脉冲（单周期宽度）
    
    //==========================================================================
    // 控制输出
    //==========================================================================
    output  wire                pack_enable,        // 打包模块使能
    output  wire                ddr_init_done_sync, // DDR3初始化完成（同步后）
    output  wire                sys_running         // 系统运行标志
);

//==============================================================================
// 内部信号定义
//==============================================================================
wire    [7:0] pps_cnt;
wire    pps_sys_running;

//==============================================================================
// 使用控制器的同域同步结果：UI→DCO两拍延迟在控制器中保持。
// 本模块不再复制同步链，PPS/打包逻辑使用同一个就绪电平。
//==============================================================================
assign ddr_init_done_sync = ddr_init_done_native;

//==============================================================================
// PPS控制模块例化
//==============================================================================
pps_ctrl u_pps_ctrl(
    .clk                (clk),
    .rst_n              (rst_n),
    .ddr_init_done      (ddr_init_done_sync),
    .pps_pulse          (pps_pulse),
    .sys_running        (pps_sys_running),
    .pps_cnt            (pps_cnt)
);

//==============================================================================
// 打包模块使能信号生成
//==============================================================================
// Gate the visible running status with synchronized DDR readiness.
assign sys_running = ddr_init_done_sync && pps_sys_running;
assign pack_enable = ddr_init_done_sync && !wfifo_wr_rst_busy && sys_running;

endmodule
