`timescale 1ns / 1ps

module baud_rate_controller(
	//==========================================================================
	// 系统信号
	//==========================================================================
	input						clk,				// 20MHz系统时钟
	input						rst_n,				// 系统复位（低有效）
	
	//==========================================================================
	// 按键输入
	//==========================================================================
	input			[2:0]		key_in,				// 按键输入[KEY2,KEY1,KEY0]
	
	//==========================================================================
	// 波特率选择输出
	//==========================================================================
	output	reg		[1:0]		Baud_Set			// 波特率选择: 00=4800, 01=9600, 10=115200
);

//==============================================================================
// 内部信号定义
//==============================================================================

reg			[2:0]			key_sync;				// 按键同步寄存器

//==============================================================================
// 按键信号同步（防止亚稳态）
//==============================================================================
always @(posedge clk or negedge rst_n) begin
	if (!rst_n)
		key_sync <= 3'b111;							// 复位时默认未按下
	else
		key_sync <= key_in;
end

//==============================================================================
// 波特率选择逻辑
//==============================================================================
always @(posedge clk or negedge rst_n) begin
	if (!rst_n) begin
		Baud_Set <= 2'd2;							// 复位默认115200
	end
	else begin
		casez (key_sync)
			3'b110: Baud_Set <= 2'd0;				// KEY0按下 → 4800
			3'b101: Baud_Set <= 2'd1;				// KEY1按下 → 9600
			3'b011: Baud_Set <= 2'd2;				// KEY2按下 → 115200
			default: Baud_Set <= Baud_Set;			// 保持原值
		endcase
	end
end

endmodule