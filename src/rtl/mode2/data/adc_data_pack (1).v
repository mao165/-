`timescale 1ns / 1ps
//******************************************************************************
//  文件名:     adc_data_pack.v
//  模块名:     adc_data_pack
//  功能描述:   ADC数据打包模块
//              - 将4个16bit采样打包成1个64bit
//              - 大端序: {sample0, sample1, sample2, sample3}
//              - ADC数据持续输入，无valid信号
//------------------------------------------------------------------------------
//  数据格式:
//  输入: 16bit采样数据，每clk一个，持续不断
//  输出: 64bit打包数据，每4个输入产生1个输出
//  
//  打包顺序 (大端序):
//  [63:48] = 第1个采样 (sample0)
//  [47:32] = 第2个采样 (sample1)
//  [31:16] = 第3个采样 (sample2)
//  [15:0]  = 第4个采样 (sample3)
//------------------------------------------------------------------------------
//  时序图:
//  clk:        ─┐ ┌─┐ ┌─┐ ┌─┐ ┌─┐ ┌─┐ ┌─┐ ┌─┐ ┌─
//               └─┘ └─┘ └─┘ └─┘ └─┘ └─┘ └─┘ └─┘
//  din:           0   1   2   3   4   5   6   7
//  (持续输入)
//  dout:              │  {0,1,2,3}  │  {4,5,6,7}  │
//  dout_valid:  ──────────────┐ ┌───────────┐ ┌───
//                             └─┘           └─┘
//------------------------------------------------------------------------------


module adc_data_pack(
    //==========================================================================
    // 系统信号
    //==========================================================================
    input   wire                clk,                // 时钟
    input   wire                rst_n,              // 复位（低有效）
    
    //==========================================================================
    // 控制信号
    //==========================================================================
    input   wire                enable,             // 打包使能
                                                    // 为1时才进行打包，为0时暂停
    
    //==========================================================================
    // 数据输入 (16bit)
    // ADC数据持续输入，无valid信号
    //==========================================================================
    input   wire    [15:0]      din,                // 16bit输入数据
    
    //==========================================================================
    // 数据输出 (64bit)
    //==========================================================================
    output  reg     [63:0]      dout,               // 64bit打包输出
    output  reg                 dout_valid,         // 输出数据有效
    
    //==========================================================================
    // 调试输出
    //==========================================================================
    output  wire    [1:0]       debug_pack_cnt      // 打包计数器（调试用）
);

//==============================================================================
// 内部信号
//==============================================================================
reg     [1:0]       pack_cnt;                       // 打包计数器 (0-3)
reg     [15:0]      din_d0;                         // 第1个采样暂存
reg     [15:0]      din_d1;                         // 第2个采样暂存
reg     [15:0]      din_d2;                         // 第3个采样暂存

//==============================================================================
// 打包计数器
// 使能时持续计数，每4个数据输出一次
//==============================================================================
always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        pack_cnt <= 2'd0;
    end
    else if (enable) begin
        pack_cnt <= pack_cnt + 1'b1;    // 自动溢出回0
    end
end

//==============================================================================
// 暂存前3个采样数据
//==============================================================================
always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        din_d0 <= 16'd0;
        din_d1 <= 16'd0;
        din_d2 <= 16'd0;
    end
    else if (enable) begin
        case (pack_cnt)
            2'd0: din_d0 <= din;        // 暂存第1个
            2'd1: din_d1 <= din;        // 暂存第2个
            2'd2: din_d2 <= din;        // 暂存第3个
            default: ;                   // 第4个直接用于打包
        endcase
    end
end

//==============================================================================
// 打包输出
// 当收到第4个数据时，输出64bit打包数据
// 大端序: 第1个在高位，第4个在低位
//==============================================================================
always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        dout       <= 64'd0;
        dout_valid <= 1'b0;
    end
    else if (enable && (pack_cnt == 2'd3)) begin
        // 收到第4个数据，打包输出
        dout       <= {din_d0, din_d1, din_d2, din};
        dout_valid <= 1'b1;
    end
    else begin
        dout_valid <= 1'b0;
    end
end

//==============================================================================
// 调试输出
//==============================================================================
assign debug_pack_cnt = pack_cnt;

endmodule
