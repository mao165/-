`timescale 1ns / 1ps


module spi(
	//==========================================================================
	// 系统接口
	//==========================================================================
	input						clk,				// SPI工作时钟
	input						rst,				// 复位信号（高有效）
	
	//==========================================================================
	// 控制接口
	//==========================================================================
	input						en,					// 传输使能（高有效，单周期脉冲启动）
	input						rw,					// 读写选择: 1=读操作, 0=写操作
	input			[14:0]		addr,				// 寄存器地址[14:0]
	input			[7:0]		wr_data,			// 写入数据[7:0]
	
	//==========================================================================
	// 状态接口
	//==========================================================================
	output	reg		[7:0]		rd_data,			// 读出数据[7:0]
	output	reg					rd_valid,			// 读数据有效标志（单周期脉冲）
	output	reg					busy,				// 忙标志: 1=传输中, 0=空闲
	
	//==========================================================================
	// SPI物理接口
	//==========================================================================
	inout						spi_sdio,			// SPI双向数据线(SDIO)
	output	reg					spi_sclk,			// SPI时钟输出
	output	reg					spi_csn				// SPI片选输出（低有效）
);

//==============================================================================
// 参数定义
//==============================================================================

// FSM状态编码
localparam	S_IDLE			= 4'd0;				// 空闲，等待使能
localparam	S_CS_SETUP		= 4'd1;				// CS建立时间
localparam	S_WRITE			= 4'd2;				// 发送数据（SCLK下降沿更新）
localparam	S_WRITE_HOLD	= 4'd3;				// 数据保持（SCLK上升沿）
localparam	S_READ_SETUP	= 4'd4;				// 读准备（切换SDIO方向）
localparam	S_READ			= 4'd5;				// 读数据（SCLK上升沿采样）
localparam	S_READ_NEXT		= 4'd6;				// 读下一位
localparam	S_CS_HOLD		= 4'd7;				// CS保持时间

// 传输位数定义
localparam	WRITE_LEN		= 5'd24;			// 写操作总位数: 1+15+8=24bit
localparam	READ_ADDR_LEN	= 5'd16;			// 读操作地址位数: 1+15=16bit
localparam	READ_DATA_LEN	= 5'd8;				// 读操作数据位数: 8bit

//==============================================================================
// 内部信号定义
//==============================================================================

// SDIO三态控制
reg							spi_sdo_en;			// 输出使能: 1=输出模式, 0=输入模式
reg							spi_sdo;			// 输出数据
wire						spi_sdi;			// 输入数据

// 数据寄存器
reg			[23:0]			tx_data;			// 发送移位寄存器

// 计数器
reg			[4:0]			bit_cnt;			// 已传输位数计数器
reg			[4:0]			transfer_len;		// 当前传输总位数

// 状态机
reg			[3:0]			state;				// 当前状态

//==============================================================================
// SDIO三态控制逻辑
//==============================================================================
// 写操作时FPGA驱动SDIO，读操作接收数据时SDIO设为高阻由从设备驱动
assign spi_sdio = spi_sdo_en ? spi_sdo : 1'bz;
assign spi_sdi  = spi_sdio;

//==============================================================================
// SPI主控状态机
//==============================================================================

always @(posedge clk or posedge rst) begin
	if (rst) begin
		// 复位: 所有寄存器恢复默认值
		rd_valid		<= 1'b0;
		rd_data			<= 8'd0;
		busy			<= 1'b0;
		tx_data			<= 24'd0;
		bit_cnt			<= 5'd0;
		transfer_len	<= 5'd0;
		state			<= S_IDLE;
		
		// SPI信号复位状态 (Mode3空闲状态)
		spi_sclk		<= 1'b1;				// CPOL=1: 空闲时钟为高
		spi_sdo_en		<= 1'b1;				// 默认输出模式
		spi_sdo			<= 1'b1;				// 默认输出高
		spi_csn			<= 1'b1;				// 片选无效(高)
	end
	else begin
		case (state)
			//------------------------------------------------------------------
			// S_IDLE: 空闲状态，等待传输使能
			//------------------------------------------------------------------
			S_IDLE: begin
				rd_valid		<= 1'b0;
				rd_data			<= 8'd0;
				bit_cnt			<= 5'd0;
				
				// 恢复SPI空闲状态
				spi_sclk		<= 1'b1;
				spi_sdo_en		<= 1'b1;
				spi_sdo			<= 1'b1;
				spi_csn			<= 1'b1;
				
				if (en) begin
					// 收到使能，准备传输
					tx_data			<= {rw, addr, wr_data};	// 组装发送帧
					transfer_len	<= rw ? READ_ADDR_LEN : WRITE_LEN;
					busy			<= 1'b1;
					state			<= S_CS_SETUP;
				end
				else begin
					transfer_len	<= 5'd0;
					tx_data			<= 24'd0;
					busy			<= 1'b0;
				end
			end
			
			//------------------------------------------------------------------
			// S_CS_SETUP: 片选建立时间 (tCSS)
			//------------------------------------------------------------------
			S_CS_SETUP: begin
				spi_csn			<= 1'b0;			// 拉低片选，选中从设备
				state			<= S_WRITE;
			end
			
			//------------------------------------------------------------------
			// S_WRITE: 发送数据 - SCLK下降沿更新SDIO
			//------------------------------------------------------------------
			S_WRITE: begin
				spi_sclk		<= 1'b0;			// SCLK拉低
				spi_sdo			<= tx_data[23 - bit_cnt];	// 输出当前位(MSB优先)
				bit_cnt			<= bit_cnt + 1'b1;
				state			<= S_WRITE_HOLD;
			end
			
			//------------------------------------------------------------------
			// S_WRITE_HOLD: 数据保持 - SCLK上升沿(从设备采样点)
			//------------------------------------------------------------------
			S_WRITE_HOLD: begin
				spi_sclk		<= 1'b1;			// SCLK拉高，从设备在此采样
				
				if (bit_cnt >= transfer_len) begin
					// 发送完成，根据读写类型决定下一步
					if (tx_data[23] == 1'b0) begin
						// 写操作完成 → 结束传输
						state	<= S_CS_HOLD;
					end
					else begin
						// 读操作 → 准备接收数据
						state	<= S_READ_SETUP;
					end
				end
				else begin
					// 继续发送下一位
					state		<= S_WRITE;
				end
			end
			
			//------------------------------------------------------------------
			// S_READ_SETUP: 读准备 - 切换SDIO为输入模式
			//------------------------------------------------------------------
			S_READ_SETUP: begin
				spi_sclk		<= 1'b0;
				bit_cnt			<= 5'd0;			// 重置位计数器
				spi_sdo_en		<= 1'b0;			// SDIO切换为输入(高阻)
				state			<= S_READ;
			end
			
			//------------------------------------------------------------------
			// S_READ: 读数据 - SCLK上升沿采样SDIO
			//------------------------------------------------------------------
			S_READ: begin
				spi_sclk				<= 1'b1;	// SCLK拉高，采样数据
				rd_data[7 - bit_cnt]	<= spi_sdi;	// 存储当前位(MSB优先)
				bit_cnt					<= bit_cnt + 1'b1;
				state					<= S_READ_NEXT;
			end
			
			//------------------------------------------------------------------
			// S_READ_NEXT: 判断是否读取完成
			//------------------------------------------------------------------
			S_READ_NEXT: begin
				if (bit_cnt >= READ_DATA_LEN) begin
					// 8位数据读取完成
					rd_valid	<= 1'b1;			// 数据有效标志
					state		<= S_CS_HOLD;
				end
				else begin
					// 继续读取下一位
					spi_sclk	<= 1'b0;			// SCLK拉低，准备下次上升沿
					state		<= S_READ;
				end
			end
			
			//------------------------------------------------------------------
			// S_CS_HOLD: 片选保持时间 (tCSH)，完成传输
			//------------------------------------------------------------------
			S_CS_HOLD: begin
				spi_csn			<= 1'b1;			// 拉高片选，释放从设备
				rd_valid		<= 1'b0;
				busy			<= 1'b0;			// 传输完成
				state			<= S_IDLE;
			end
			
			//------------------------------------------------------------------
			// default: 异常状态恢复
			//------------------------------------------------------------------
			default: begin
				state			<= S_IDLE;
			end
		endcase
	end
end

endmodule
